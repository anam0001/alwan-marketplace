-- Alwan: Creator registrations
-- Run this once in the Supabase SQL Editor.

create table if not exists public.creators (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  name text not null,
  city text not null,
  skill text not null,
  description text not null,
  portfolio_files jsonb not null default '[]'::jsonb,
  rating numeric(2,1) not null default 0,
  reviews integer not null default 0,
  image text not null default '',
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.creators add column if not exists user_id uuid references auth.users(id) on delete cascade;
alter table public.creators alter column status set default 'pending';
drop index if exists idx_creators_user_id;
create unique index idx_creators_user_id on public.creators(user_id);

create index if not exists idx_creators_status on public.creators(status);
create index if not exists idx_creators_created_at on public.creators(created_at desc);
create index if not exists idx_creators_skill on public.creators(skill);

-- Storage bucket for portfolio images.
insert into storage.buckets (id, name, public)
values ('creator-portfolios', 'creator-portfolios', true)
on conflict (id) do update set public = true;

alter table public.creators enable row level security;

drop policy if exists "Public can view approved creators" on public.creators;
create policy "Public can view approved creators"
  on public.creators for select
  using (status = 'approved');

drop policy if exists "Creators can manage own profile" on public.creators;
create policy "Creators can manage own profile"
  on public.creators for all
  using (auth.uid() = user_id)
  with check (auth.uid() = user_id);

drop policy if exists "Authenticated users can upload portfolios" on storage.objects;
create policy "Authenticated users can upload portfolios"
  on storage.objects for insert to authenticated
  with check (bucket_id = 'creator-portfolios' and (storage.foldername(name))[1] = auth.uid()::text);

drop policy if exists "Public can view portfolios" on storage.objects;
create policy "Public can view portfolios"
  on storage.objects for select to public
  using (bucket_id = 'creator-portfolios');
