-- Alwan order lifecycle: request -> accepted -> in_progress -> completed
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  customer_id uuid not null references auth.users(id) on delete cascade,
  creator_id bigint not null references public.creators(id) on delete restrict,
  title text not null,
  details text not null,
  amount numeric(12,2) not null default 0,
  status text not null default 'requested' check (status in ('requested','accepted','in_progress','completed','cancelled','rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_notifications (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  recipient_id uuid not null references auth.users(id) on delete cascade,
  message text not null,
  read_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.order_reviews (
  id bigint generated by default as identity primary key,
  order_id bigint not null unique references public.orders(id) on delete cascade,
  customer_id uuid not null references auth.users(id) on delete cascade,
  creator_id bigint not null references public.creators(id) on delete cascade,
  rating integer not null check (rating between 1 and 5),
  review text not null,
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_customer on public.orders(customer_id, created_at desc);
create index if not exists idx_orders_creator on public.orders(creator_id, created_at desc);
create index if not exists idx_order_notifications_recipient on public.order_notifications(recipient_id, created_at desc);

alter table public.orders enable row level security;
alter table public.order_notifications enable row level security;
alter table public.order_reviews enable row level security;

